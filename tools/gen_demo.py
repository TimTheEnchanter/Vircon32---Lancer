"""Turns the demo recorded on a Lancer memory card into demo_builtin.h.

Usage: python3 tools/gen_demo.py CARD [OUT]

Record the game with a build that has no built-in demo (so the game is
saved to the card when it ends), e.g. the in-ROM autopilot test build."""
import struct, sys
REC_WORDS = 720
d = open(sys.argv[1], 'rb').read()
w = lambda i: struct.unpack('<i', d[8 + 4 * i:12 + 4 * i])[0]
seed, frames, score = w(31), w(32), w(33)
data = [w(40 + i) for i in range(REC_WORDS)]
rows = ',\n    '.join(', '.join('0x%08X' % (v & 0xFFFFFFFF) for v in data[i:i + 8]) for i in range(0, REC_WORDS, 8))
out = sys.argv[2] if len(sys.argv) > 2 else 'demo_builtin.h'
open(out, 'w').write(f'''// generated by tools/gen_demo.py: the recording shown in attract mode
// until a player sets a better game (score {score}, {frames} frames)
int builtin_demo_seed = {seed};
int builtin_demo_frames = {frames};
int builtin_demo_score = {score};
int[ REC_WORDS ] builtin_demo_data =
{{
    {rows}
}};
''')
print('seed', seed, 'frames', frames, 'score', score)
